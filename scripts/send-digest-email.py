def markdown_to_html(md_text: str) -> str:
    """Convert markdown to styled HTML email."""
    html_content = markdown.markdown(
        md_text,
        extensions=["tables", "fenced_code", "codehilite"],
    )
    return HTML_TEMPLATE.format(content=html_content)


def send_email(to: str, subject: str, html_body: str) -> dict:
    """Send an HTML email via Resend API."""
    api_key = os.environ.get("RESEND_API_KEY")
    if not api_key:
        print("Error: RESEND_API_KEY environment variable is not set.", file=sys.stderr)
        print("Set it in your .env file or export it:", file=sys.stderr)
        print("  export RESEND_API_KEY=re_xxxxxxxxxxxxx", file=sys.stderr)
        sys.exit(1)

    from_email = os.environ.get("DIGEST_FROM_EMAIL")
    if not from_email:
        print("Error: DIGEST_FROM_EMAIL environment variable is not set.", file=sys.stderr)
        print("Set it to a verified sender address in Resend.", file=sys.stderr)
        sys.exit(1)

    resend.api_key = api_key

    params: resend.Emails.SendParams = {
        "from": from_email,
        "to": [to],
        "subject": subject,
        "html": html_body,
    }

    result = resend.Emails.send(params)
    return result


def main():
    parser = argparse.ArgumentParser(description="Send a markdown digest as HTML email via Resend")
    parser.add_argument("--to", required=True, help="Recipient email address")
    parser.add_argument("--subject", required=True, help="Email subject line")
    parser.add_argument("--body-file", help="Path to markdown file to send")
    parser.add_argument("--body", help="Inline markdown content to send")
    parser.add_argument("--save-html", help="Also save the HTML to this path")
    args = parser.parse_args()

    # Read markdown content
    if args.body_file:
        md_text = Path(args.body_file).read_text(encoding="utf-8")
    elif args.body:
        md_text = args.body
    else:
        print("Error: provide either --body-file or --body", file=sys.stderr)
        sys.exit(1)

    # Convert to HTML
    html_body = markdown_to_html(md_text)

    # Optionally save HTML
    if args.save_html:
        Path(args.save_html).write_text(html_body, encoding="utf-8")
        print(f"HTML saved to: {args.save_html}")

    # Send email
    result = send_email(args.to, args.subject, html_body)
    print(f"Email sent successfully. ID: {result.get('id', 'unknown')}")


if __name__ == "__main__":
    main()
