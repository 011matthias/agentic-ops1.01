"""
Send a markdown digest as a styled HTML email via Resend API.

Usage:
    uv run scripts/send-digest-email.py --to user@example.com --subject "Subject" --body-file digest.md
    uv run scripts/send-digest-email.py --to user@example.com --subject "Subject" --body "# Hello"

Environment variables:
    RESEND_API_KEY      - Required. Resend API key.
    DIGEST_FROM_EMAIL   - Required. Verified sender address.
"""

import argparse
import os
import sys
from pathlib import Path

import markdown
import resend

